// Generate golden vectors for the Hazard3 zfinx_golden software test, using
// Berkeley SoftFloat (RISC-V specialisation) as the reference.
//
//   gen_zfinx_vectors <count> <seed> > zfinx_vectors.h
//
// SPDX-License-Identifier: Apache-2.0

#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <random>

extern "C" {
#include "softfloat.h"
}

// Must match the op numbering in hazard3/test/sim/sw_testcases/zfinx_golden.c
enum Op {
	ADD, SUB, MUL, MADD, MSUB, NMSUB, NMADD, DIV, SQRT, SGNJ, SGNJN, SGNJX,
	MIN, MAX, EQ, LT, LE, CLASS, CVT_W_S, CVT_WU_S, CVT_S_W, CVT_S_WU, NUM_OPS
};

static const char *op_names[NUM_OPS] = {
	"add", "sub", "mul", "madd", "msub", "nmsub", "nmadd", "div", "sqrt",
	"sgnj", "sgnjn", "sgnjx", "min", "max", "eq", "lt", "le", "class",
	"cvt_w_s", "cvt_wu_s", "cvt_s_w", "cvt_s_wu"
};

static bool uses_rm(int op) {
	return op <= SQRT || op >= CVT_W_S;
}

static inline bool is_nan(uint32_t x)  { return (x & 0x7f800000u) == 0x7f800000u && (x & 0x7fffffu); }
static inline bool is_snan(uint32_t x) { return is_nan(x) && !(x & 0x400000u); }
static inline float32_t F(uint32_t x)  { float32_t f; f.v = x; return f; }

static uint32_t fclass(uint32_t x) {
	bool s = x >> 31;
	uint32_t e = (x >> 23) & 0xff, f = x & 0x7fffff;
	if (e == 0xff)
		return f ? ((f & 0x400000) ? 1u << 9 : 1u << 8) : (s ? 1u << 0 : 1u << 7);
	if (e == 0)
		return f ? (s ? 1u << 2 : 1u << 5) : (s ? 1u << 3 : 1u << 4);
	return s ? 1u << 1 : 1u << 6;
}

static uint32_t model(int op, int rm, uint32_t a, uint32_t b, uint32_t c, uint32_t &flags) {
	softfloat_roundingMode = rm;
	softfloat_detectTininess = softfloat_tininess_afterRounding;
	softfloat_exceptionFlags = 0;
	const uint32_t S = 0x80000000u;
	uint32_t r = 0;
	switch (op) {
	case ADD:   r = f32_add(F(a), F(b)).v; break;
	case SUB:   r = f32_sub(F(a), F(b)).v; break;
	case MUL:   r = f32_mul(F(a), F(b)).v; break;
	case MADD:  r = f32_mulAdd(F(a), F(b), F(c)).v; break;
	case MSUB:  r = f32_mulAdd(F(a), F(b), F(c ^ S)).v; break;
	case NMSUB: r = f32_mulAdd(F(a ^ S), F(b), F(c)).v; break;
	case NMADD: r = f32_mulAdd(F(a ^ S), F(b), F(c ^ S)).v; break;
	case DIV:   r = f32_div(F(a), F(b)).v; break;
	case SQRT:  r = f32_sqrt(F(a)).v; break;
	case SGNJ:  r = (a & ~S) | (b & S); break;
	case SGNJN: r = (a & ~S) | (~b & S); break;
	case SGNJX: r = a ^ (b & S); break;
	case MIN:
	case MAX: {
		uint32_t fl = (is_snan(a) || is_snan(b)) ? softfloat_flag_invalid : 0;
		if (is_nan(a) && is_nan(b))      r = 0x7fc00000u;
		else if (is_nan(a))              r = b;
		else if (is_nan(b))              r = a;
		else {
			bool eq = f32_eq(F(a), F(b));
			bool pick_a = op == MIN
				? (f32_lt_quiet(F(a), F(b)) || (eq &&  (a & S)))
				: (f32_lt_quiet(F(b), F(a)) || (eq && !(a & S)));
			r = pick_a ? a : b;
		}
		softfloat_exceptionFlags = fl;
		break;
	}
	case EQ:       r = f32_eq(F(a), F(b)); break;
	case LT:       r = f32_lt(F(a), F(b)); break;
	case LE:       r = f32_le(F(a), F(b)); break;
	case CLASS:    r = fclass(a); break;
	case CVT_W_S:  r = (uint32_t)f32_to_i32(F(a), rm, true); break;
	case CVT_WU_S: r = f32_to_ui32(F(a), rm, true); break;
	case CVT_S_W:  r = i32_to_f32((int32_t)a).v; break;
	case CVT_S_WU: r = ui32_to_f32(a).v; break;
	}
	flags = softfloat_exceptionFlags & 0x1f;
	return r;
}

static std::mt19937_64 rng;
static uint32_t rnd32() { return (uint32_t)rng(); }
static uint32_t rnd_range(uint32_t lo, uint32_t hi) { return lo + rnd32() % (hi - lo + 1); }

static uint32_t rnd_f32() {
	uint32_t s = (rnd32() & 1) << 31;
	uint32_t f = rnd32() & 0x7fffff;
	uint32_t w = rnd32() % 100;
	if (w < 6)  return s;
	if (w < 14) return s | (f ? f : 1);
	if (w < 18) return s | 0x7f800000;
	if (w < 21) return s | 0x7fc00000 | (f & 0x3fffff);
	if (w < 24) return s | 0x7f800000 | ((f & 0x3fffff) ? (f & 0x3fffff) : 1);
	if (w < 55) return s | rnd_range(1, 254) << 23 | f;
	if (w < 85) return s | rnd_range(117, 137) << 23 | f;
	if (w < 92) return s | (rnd32() & 1 ? rnd_range(1, 6) : rnd_range(249, 254)) << 23 | f;
	return rnd32();
}

static uint32_t rnd_int() {
	uint32_t bits = rnd32() % 33;
	uint32_t v = bits ? rnd32() >> (32 - bits) : 0;
	return rnd32() & 1 ? -v : v;
}

int main(int argc, char **argv) {
	if (argc < 3) {
		fprintf(stderr, "usage: %s <count> <seed>\n", argv[0]);
		return 1;
	}
	int count = atoi(argv[1]);
	rng.seed(strtoull(argv[2], nullptr, 0));

	printf("// Golden Zfinx test vectors (op, rm, a, b, c -> result, fflags): %d vectors, seed %s.\n", count, argv[2]);
	printf("// Generated by hazard3_fpu verif/zfinx/gen_zfinx_vectors.cpp using\n");
	printf("// Berkeley SoftFloat (RISC-V specialisation). Do not edit.\n\n");
	printf("#ifndef _ZFINX_VECTORS_H\n#define _ZFINX_VECTORS_H\n\n#include <stdint.h>\n\n");
	printf("typedef struct {\n\tuint8_t op, rm, flags, pad;\n\tuint32_t a, b, c, result;\n} zfinx_vec_t;\n\n");
	printf("#define ZFINX_N_VECS %d\n\n", count);
	printf("static const zfinx_vec_t zfinx_vecs[ZFINX_N_VECS] = {\n");
	for (int i = 0; i < count; ++i) {
		int op = i % NUM_OPS;  // every op equally, interleaved
		int rm = uses_rm(op) ? (int)(rnd32() % 5) : 0;
		uint32_t a = rnd_f32(), b = rnd_f32(), c = rnd_f32();
		if (op == CVT_S_W || op == CVT_S_WU)
			a = rnd_int();
		if ((op == CVT_W_S || op == CVT_WU_S) && rnd32() % 2)
			a = (rnd32() & 0x80000000u) | rnd_range(124, 160) << 23 | (rnd32() & 0x7fffff);
		if ((op >= MADD && op <= NMADD) && rnd32() % 4 == 0) {
			softfloat_roundingMode = 0;
			uint32_t p = f32_mul(F(a), F(b)).v;
			bool want_neg = op == MADD || op == NMADD, flip = op == NMSUB || op == NMADD;
			c = (p ^ ((want_neg != flip) ? 0x80000000u : 0)) + (rnd32() % 5) - 2;
		}
		uint32_t flags;
		uint32_t r = model(op, rm, a, b, c, flags);
		printf("\t{%2d, %d, 0x%02x, 0, 0x%08x, 0x%08x, 0x%08x, 0x%08x}, // %s\n",
			op, rm, flags, a, b, c, r, op_names[op]);
	}
	printf("};\n\n#endif\n");
	return 0;
}
